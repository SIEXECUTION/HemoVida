BEGIN;
DO $$ BEGIN
 IF to_regprocedure('public.hemo_lote_aprobado(integer)') IS NULL THEN
  RAISE EXCEPTION 'Se requiere migracion 06';
 END IF;
END $$;
CREATE TABLE IF NOT EXISTS public.agendaturno (
 idturno integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inicio timestamptz NOT NULL UNIQUE,
 fin timestamptz NOT NULL,
 cupo integer NOT NULL CHECK(cupo BETWEEN 1 AND 500),
 habilitado boolean NOT NULL DEFAULT true,
 creadopor integer NOT NULL REFERENCES public.usuario(idusuario),
 CHECK(fin>inicio AND fin<=inicio+interval '24 hours')
);
ALTER TABLE public.citadonacion ADD COLUMN IF NOT EXISTS idturno integer REFERENCES public.agendaturno(idturno);
ALTER TABLE public.citadonacion DROP CONSTRAINT IF EXISTS citadonacion_estadocita_check;
ALTER TABLE public.citadonacion ADD CONSTRAINT citadonacion_estadocita_check
 CHECK(estadocita IN ('Programada','Atendida','Cancelada','Inasistencia','Pendiente'));
-- NULL conserva la falta de clasificación de las citas históricas.
ALTER TABLE public.citadonacion ADD COLUMN IF NOT EXISTS tipoatencion varchar(20)
 CHECK(tipoatencion IN ('Evaluacion','Donacion'));
CREATE INDEX IF NOT EXISTS ix_cita_turno_ciclo2 ON public.citadonacion(idturno,estadocita);
CREATE TABLE IF NOT EXISTS public.prefiltrocita (
 idcita integer PRIMARY KEY REFERENCES public.citadonacion(idcita),
 idusuario integer NOT NULL REFERENCES public.usuario(idusuario),
 versioncatalogo varchar(64) NOT NULL,
 catalogo jsonb NOT NULL CHECK(jsonb_typeof(catalogo)='array'),
 respuestas jsonb NOT NULL CHECK(jsonb_typeof(respuestas)='array'),
 aprobado boolean NOT NULL,
 fecharegistro timestamptz NOT NULL DEFAULT now()
);
-- Acceso mediante la API Django; sin políticas públicas de datos personales.
-- El propietario de las tablas (conexión backend actual) conserva acceso.
ALTER TABLE public.agendaturno ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.prefiltrocita ENABLE ROW LEVEL SECURITY;
DO $$ DECLARE t text; k text; BEGIN
 FOR t,k IN SELECT * FROM (VALUES ('agendaturno','idturno'),('prefiltrocita','idcita')) x(t,k) LOOP
  EXECUTE format('DROP TRIGGER IF EXISTS trg_hemo_auditoria ON public.%I',t);
  EXECUTE format('CREATE TRIGGER trg_hemo_auditoria AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.hemo_auditar_cambio(%L)',t,k);
 END LOOP;
END $$;
COMMIT;
