BEGIN;
DO $$ BEGIN
 IF to_regclass('public.prefiltrocita') IS NULL OR to_regclass('public.colectaautologa') IS NULL THEN
  RAISE EXCEPTION 'Se requieren migraciones 07 y 08';
 END IF;
END $$;
ALTER TABLE public.requisitodonacion ADD COLUMN IF NOT EXISTS activo boolean NOT NULL DEFAULT true;
CREATE TABLE IF NOT EXISTS public.cierreagenda(
 idcierre integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fecha date NOT NULL UNIQUE,
 cerrado boolean NOT NULL DEFAULT true,
 motivo varchar(250) NOT NULL,
 idusuario integer NOT NULL REFERENCES public.usuario(idusuario),
 actualizado timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.programacionautologa(
 idprograma integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 idreceptor integer NOT NULL REFERENCES public.receptor(idpersona),
 fechacirugia date NOT NULL,
 indicacion text NOT NULL,
 referenciamedica varchar(120) NOT NULL,
 idmedico integer NOT NULL REFERENCES public.personalsalud(idpersona),
 estado varchar(25) NOT NULL DEFAULT 'PendienteRevision'
  CHECK(estado IN ('PendienteRevision','Aprobada','RevisionRequerida','Cancelada','Cerrada')),
 version integer NOT NULL DEFAULT 1 CHECK(version>0),
 revisadopor integer REFERENCES public.personalsalud(idpersona),
 fecharevision timestamptz,
 motivorevision varchar(500),
 creado timestamptz NOT NULL DEFAULT now(),
 actualizado timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_programa_autologo_activo ON public.programacionautologa(idreceptor)
 WHERE estado NOT IN ('Cancelada','Cerrada');
CREATE TABLE IF NOT EXISTS public.programacionautologahistorial(
 idhistorial integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 idprograma integer NOT NULL REFERENCES public.programacionautologa(idprograma),
 version integer NOT NULL,
 contenido jsonb NOT NULL,
 idusuario integer NOT NULL REFERENCES public.usuario(idusuario),
 registrado timestamptz NOT NULL DEFAULT now(),
 UNIQUE(idprograma,version)
);
ALTER TABLE public.citadonacion ADD COLUMN IF NOT EXISTS idprograma integer REFERENCES public.programacionautologa(idprograma);
ALTER TABLE public.colectaautologa ADD COLUMN IF NOT EXISTS idprograma integer REFERENCES public.programacionautologa(idprograma);
ALTER TABLE public.citadonacion DROP CONSTRAINT IF EXISTS citadonacion_tipoatencion_check;
ALTER TABLE public.citadonacion ADD CONSTRAINT citadonacion_tipoatencion_check
 CHECK(tipoatencion IN ('Evaluacion','Donacion','Autologa'));
CREATE INDEX IF NOT EXISTS ix_cita_programa ON public.citadonacion(idprograma);
CREATE INDEX IF NOT EXISTS ix_colecta_programa ON public.colectaautologa(idprograma);
CREATE TABLE IF NOT EXISTS public.prefiltroborrador(
 idpersona integer PRIMARY KEY REFERENCES public.posibledonador(idpersona),
 idusuario integer NOT NULL REFERENCES public.usuario(idusuario),
 versioncatalogo varchar(64) NOT NULL,
 catalogo jsonb NOT NULL CHECK(jsonb_typeof(catalogo)='array'),
 respuestas jsonb NOT NULL CHECK(jsonb_typeof(respuestas)='array'),
 idturno integer REFERENCES public.agendaturno(idturno),
 tipoatencion varchar(20) NOT NULL CHECK(tipoatencion IN ('Evaluacion','Donacion','Autologa')),
 idprograma integer REFERENCES public.programacionautologa(idprograma),
 actualizado timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.cierreagenda ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.programacionautologa ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.programacionautologahistorial ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.prefiltroborrador ENABLE ROW LEVEL SECURITY;
DO $$ DECLARE t text; k text; BEGIN
 FOR t,k IN SELECT * FROM (VALUES ('cierreagenda','idcierre'),('programacionautologa','idprograma'),
 ('prefiltroborrador','idpersona'),('requisitodonacion','idrequisito')) x(t,k) LOOP
  EXECUTE format('DROP TRIGGER IF EXISTS trg_hemo_auditoria ON public.%I',t);
  EXECUTE format('CREATE TRIGGER trg_hemo_auditoria AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.hemo_auditar_cambio(%L)',t,k);
 END LOOP;
END $$;
COMMIT;
